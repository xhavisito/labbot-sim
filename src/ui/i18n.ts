export function setLang(l: 'es' | 'en'): void {
  lang = l;
  try {
    localStorage.setItem('labbot.lang', l);
  } catch {
    /* sin almacenamiento */
  }
}
export const getLang = (): 'es' | 'en' => lang;

/** Texto traducido; `{x}` se reemplaza con `vars.x`. */
export function t(k: Key, vars?: Record<string, string | number>): string {
  let s: string = (lang === 'en' ? EN : ES)[k];
  if (vars) for (const [n, v] of Object.entries(vars)) s = s.replaceAll(`{${n}}`, String(v));
  return s;
}
